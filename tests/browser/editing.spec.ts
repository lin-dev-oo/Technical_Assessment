import { test, expect } from '@playwright/test';
import { Pool } from 'pg';
const header = 'postId,id,name,email,body\n';

test.beforeEach(async ({ request }) => {
  const pool = new Pool({ connectionString: process.env.TEST_DATABASE_URL });
  try { await pool.query('TRUNCATE alternatives, comments, upload_requests'); } finally { await pool.end(); }
  await request.post('/api/uploads', { headers: { 'x-upload-id': 'seed' }, data: header + '1,1,Accepted name,accepted@example.com,Accepted body' });
});

test('edits non-identifier fields with explicit Save and Cancel', async ({ page, request }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  const form = page.getByRole('form', { name: 'Edit record 1', exact: true });
  await expect(page.getByLabel('ID', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('row', { name: 'Editing record 1', exact: true }).getByLabel('name', { exact: true })).toBeVisible();
  await page.getByLabel('name', { exact: true }).fill('My unsaved name');
  await form.getByRole('button', { name: 'Cancel', exact: true }).click();
  expect((await (await request.get('/api/comments')).json()).comments[0].name).toBe('Accepted name');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  await expect(page.getByLabel('name', { exact: true })).toHaveValue('Accepted name');
  await page.getByLabel('postId', { exact: true }).fill('2');
  await page.getByLabel('name', { exact: true }).fill('Saved name');
  await page.getByLabel('email', { exact: true }).fill('saved@example.com');
  await page.getByLabel('body', { exact: true }).fill('Saved body\nAnother line');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: testInfo.outputPath('edit-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByText('Scroll across the table to edit fields and reach Save / Cancel.')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('edit-mobile.png'), fullPage: true });
  await form.getByRole('button', { name: 'Cancel', exact: true }).scrollIntoViewIfNeeded();
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeInViewport();
  await expect(form.getByRole('button', { name: 'Cancel', exact: true })).toBeInViewport();
  await page.getByLabel('body', { exact: true }).scrollIntoViewIfNeeded();
  await expect(page.getByLabel('body', { exact: true })).toBeInViewport();
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeInViewport();
  await page.screenshot({ path: testInfo.outputPath('edit-mobile-actions.png'), fullPage: true });
  await form.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(form).toHaveCount(0);
  await expect(page.getByText('Saved name', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Saved name', { exact: true })).toBeVisible();
});

test('preserves a stale draft, compares on demand, and requires an explicit save after review', async ({ page, browser }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  const draft = 'My preserved draft\n' + 'LongDraft'.repeat(70);
  await page.getByLabel('body', { exact: true }).fill(draft);
  const other = await browser.newPage();
  await other.goto('/');
  await other.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  await other.getByLabel('body', { exact: true }).fill('Other saved body');
  await other.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toHaveAttribute('title', 'Resolve changes before saving', { timeout: 3000 });
  await expect(page.getByText('Updated in another session', { exact: true })).toBeVisible();
  await expect(page.locator('.edit-feedback-row .feedback')).toHaveCount(0);
  await page.screenshot({ path: testInfo.outputPath('stale-row-desktop.png') });
  await page.getByRole('button', { name: 'Review changes', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Review changes', exact: true });
  await expect(dialog.getByRole('region', { name: 'Draft comparison' })).toContainText('Other saved body');
  await expect(dialog).toContainText('My preserved draft');
  await page.screenshot({ path: testInfo.outputPath('stale-comparison-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: testInfo.outputPath('stale-comparison-mobile.png') });
  await dialog.getByRole('button', { name: 'Keep my changes', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByLabel('body', { exact: true })).toHaveValue(draft);
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled();
  await expect(other.locator('.body-preview')).toHaveText('Other saved body');
  await page.getByRole('searchbox').fill('no-match');
  await expect(page.getByText('No records found', { exact: true })).toBeVisible();
  await expect(page.getByLabel('body', { exact: true })).toHaveValue(draft);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('form')).toHaveCount(0);
  await page.getByRole('button', { name: 'Clear search', exact: true }).click();
  await expect(page.getByText('My preserved draft', { exact: false })).toBeVisible();
  await other.close();
});

test('preserves a failed draft and blocks it until an incoming conflict is resolved', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  const form = page.getByRole('form', { name: 'Edit record 1', exact: true });
  await page.getByLabel('body', { exact: true }).fill('Draft survives errors');
  await page.getByLabel('email', { exact: true }).fill('invalid');
  await form.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('[data-sonner-toast]')).toContainText('Check the highlighted fields.');
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Draft survives errors');
  await page.getByLabel('email', { exact: true }).fill('accepted@example.com');
  await page.route('**/api/comments/1/edit', route => route.abort());
  await form.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.locator('[data-sonner-toast]')).toContainText('Save not confirmed.');
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Draft survives errors');
  await page.unroute('**/api/comments/1/edit');
  await request.post('/api/uploads', { headers: { 'x-upload-id': 'pending' }, data: header + '2,1,Alternative,other@example.com,Other body' });
  await expect(page.getByText('This record needs conflict review.', { exact: true })).toBeVisible({ timeout: 3000 });
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Draft survives errors');
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Review conflict', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: 'Alternative 1' }).check();
  await dialog.getByRole('button', { name: /^(Keep current version|Use alternative \d+|Use selected version)$/, exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Review changes', exact: true }).click();
  await page.getByRole('button', { name: 'Keep my changes', exact: true }).click();
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Draft survives errors');
  await form.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(form).toHaveCount(0);
  await expect(page.getByText('Draft survives errors', { exact: true })).toBeVisible();
  await request.post('/api/uploads', { headers: { 'x-upload-id': 'later-pending' }, data: header + '3,1,Later,later@example.com,Later body' });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit record 1', exact: true })).toBeDisabled();
});

test('requires deliberate baseline refresh after a conflict is resolved keeping accepted values', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  const form = page.getByRole('form', { name: 'Edit record 1', exact: true });
  await page.getByLabel('body', { exact: true }).fill('Kept draft');
  await request.post('/api/uploads', { headers: { 'x-upload-id': 'conflict' }, data: header + '2,1,Alternative,other@example.com,Other body' });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Review conflict', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: 'Current version' }).check();
  await dialog.getByRole('button', { name: /^(Keep current version|Use alternative \d+|Use selected version)$/, exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: /^Review conflicts/ })).toHaveCount(0);
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Review changes', exact: true }).click();
  await page.getByRole('button', { name: 'Keep my changes', exact: true }).click();
  await expect(form.getByRole('button', { name: 'Save', exact: true })).toBeEnabled();
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Kept draft');
});


test('associates validation with inputs, restores focus, and warns before discarding changes', async ({ page }) => {
  await page.goto('/');
  const edit = page.getByRole('button', { name: 'Edit record 1', exact: true });
  await edit.click();
  await page.getByLabel('email', { exact: true }).fill('invalid');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const email = page.getByLabel('email', { exact: true });
  await expect(email).toHaveAttribute('aria-invalid', 'true');
  await expect(email).toBeFocused();
  await expect(email).toHaveAccessibleDescription('Use a valid email address.');
  const dialogPromise = page.waitForEvent('dialog');
  const reload = page.reload({ timeout: 2000 }).catch(() => {});
  const dialog = await dialogPromise;
  expect(dialog.type()).toBe('beforeunload');
  await dialog.dismiss();
  await reload;
  await expect(email).toHaveValue('invalid');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(edit).toBeFocused();
  await edit.click();
  await page.getByLabel('name', { exact: true }).fill('Updated');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(edit).toBeFocused();
});


test('can explicitly adopt current values and dismiss comparison without losing the draft', async ({ page, request }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Edit record 1', exact: true }).click();
  await page.getByLabel('name', { exact: true }).fill('My name');
  await request.post('/api/comments/1/edit', { data: { expectedVersion: 1, postId: 1, name: 'Other name', email: 'accepted@example.com', body: 'Other body' } });
  await page.getByRole('button', { name: 'Review changes', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Review changes', exact: true });
  await expect(dialog).toContainText('My name');
  await expect(dialog).toContainText('Other name');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByLabel('name', { exact: true })).toHaveValue('My name');
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toHaveAttribute('title', 'Resolve changes before saving');
  await page.getByRole('button', { name: 'Review changes', exact: true }).click();
  await dialog.getByRole('button', { name: 'Use current values', exact: true }).click();
  await expect(page.getByLabel('name', { exact: true })).toHaveValue('Other name');
  await expect(page.getByLabel('body', { exact: true })).toHaveValue('Other body');
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeEnabled();
  expect((await (await request.get('/api/comments')).json()).comments[0].version).toBe(2);
});
